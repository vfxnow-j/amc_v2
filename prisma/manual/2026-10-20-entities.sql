ALTER TABLE users ADD COLUMN IF NOT EXISTS "entityAccess" BOOLEAN NOT NULL DEFAULT false;
ALTER TABLE users ADD COLUMN IF NOT EXISTS "entityScope" TEXT NOT NULL DEFAULT 'SELECTED';

CREATE TABLE IF NOT EXISTS entities (
  id TEXT PRIMARY KEY,
  name TEXT NOT NULL,
  slug TEXT NOT NULL UNIQUE,
  "dbName" TEXT NOT NULL UNIQUE,
  modules TEXT[] NOT NULL DEFAULT ARRAY['INVENTORY'],
  active BOOLEAN NOT NULL DEFAULT true,
  "schemaVersion" INTEGER NOT NULL DEFAULT 0,
  "contactName" TEXT, email TEXT, phone TEXT, address TEXT, notes TEXT,
  "createdAt" TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
  "updatedAt" TIMESTAMP(3) NOT NULL
);

CREATE TABLE IF NOT EXISTS user_entities (
  "userId" TEXT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  "entityId" TEXT NOT NULL REFERENCES entities(id) ON DELETE CASCADE,
  PRIMARY KEY ("userId", "entityId")
);
